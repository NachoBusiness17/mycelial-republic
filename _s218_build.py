def group_of(path: str) -> str:
    segs = [s for s in path.split("?")[0].split("/") if s]
    if segs and segs[0] == "api":
        if len(segs) >= 2 and segs[1] == "v1":
            return segs[2] if len(segs) >= 3 else "index"
        return segs[1] if len(segs) >= 3 else "index"
    return "index"

def clean(s: str) -> str:
    return str(s).replace("\u2014", "-").replace("\u2013", "-").replace("|", "\\|")

def shape_cell(r: dict) -> str:
    if r.get("primary_keys"):
        keys = [clean(k) for k in r["primary_keys"]]
        shown = ", ".join(keys[:8])
        if len(keys) > 8:
            shown += f" (+{len(keys)-8} more)"
        return shown
    if r.get("delegates"):
        return "delegates: " + ", ".join(clean(d) for d in r["delegates"])
    return "dynamic (dict built at runtime, no static literal at return)"

