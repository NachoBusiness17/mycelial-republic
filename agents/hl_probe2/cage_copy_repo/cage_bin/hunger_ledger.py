# CAGE COPY (watch/cage_bin/) of scripts/hunger_ledger.py — watch/ is container-
# mounted, scripts/ is not. Sync me when the canonical changes. (09-04, lane_runner
# topology fix: recurring work runs in-cage, headless; operator order 2026-09-04.)
# Mimosa fix vs canonical: pathlib + resolve + parent containment on the write path.
"""hunger_ledger (cage copy) — nightly restock-vs-consumption gauge for watch/.

Method ($0 cash, zero model calls, pure filesystem):
  RESTOCK       watch/ files carrying the date token `_YYYYMMDD` in the filename
                (the fleet's card-naming convention; INTAKE_* subset counted too).
  CONSUMPTION   of that day's cards, those carrying a disposition marker — a
                score/verdict/route/fold/stamp band (regex list below). Cards with
                no marker are ON THE SHELF (undispositioned). HEURISTIC: the marker
                test is text-based, inclusive by design; it can over-count
                dispositions (a passing mention of "route" passes) and cannot see
                back-room consumption. Treat counts as a gauge, not a bill.
  BACKLOG TOUCH watch/ files modified on the date that do NOT carry the date token
                (older cards touched today — evidence of backlog consumption).
  SHELF         total files currently in watch/.

Output: one dated row appended to watch/HUNGER_LEDGER.md (table). Re-running the
same date REPLACES that date's row (idempotent per day).
"""

import argparse
import datetime as dt
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent.parent
WATCH = (REPO / "watch").resolve()
LEDGER = WATCH / "HUNGER_LEDGER.md"


def _safe_ledger() -> Path:
    """Mimosa path-traversal guard: ledger must live directly inside watch/."""
    if LEDGER.parent != WATCH:
        raise ValueError(f"ledger path escapes watch/: {LEDGER}")
    return LEDGER


# Disposition markers — evidence a lane gave the card a verdict/route/score.
# Case-insensitive. Inclusive by design (gauge, not bill).
MARKER_RES = [re.compile(p, re.I) for p in (
    r"\bscore\b", r"\bverdict\b", r"tri-state", r"tri state",
    r"\broute\b", r"disposition", r"\bfold(ed|ing|s)?\b",
    r"\bwindowed\b", r"\breject\b", r"\bremember\b", r"\blaunched?\b",
    r"\bband\b", r"\bstamp\b",
)]

HEADER = """# HUNGER LEDGER — restock vs consumption, per day (from 2026-09-04)

The fleet's fuel gauge. FOOD (new signal cards) vs METABOLISM (cards given a
verdict/route). Generated by `watch/cage_bin/hunger_ledger.py` (cage copy of
scripts/hunger_ledger.py) — $0, zero model calls.

Reading a row:
- **new** = watch/ cards filed that day (filename date token); **intake** = the
  INTAKE_* research-signal subset of those.
- **disp** = of the day's new cards, how many carry a disposition marker
  (score/verdict/route/fold/stamp). **gap** = new - disp = cards still on the
  shelf undispositioned (listed under the table for the day's row, latest run).
- **btouch** = older (non-date-token) watch/ files modified that day — backlog
  consumption evidence. **shelf** = total files in watch/ at run time.
- Counts are a HEURISTIC gauge (text markers), not a metered bill. Tri-state:
  counts Supported (deterministic from disk); disposition semantics Unproven.

Economist law: Max key #2 requires demonstrated starvation — restock cannot
fill the lanes for N consecutive windows. This ledger is that instrument.
"""


def day_token(day: dt.date) -> str:
    return day.strftime("%Y%m%d")


def is_dispositioned(path: Path) -> bool:
    try:
        text = path.read_text(encoding="utf-8", errors="ignore")
    except OSError:
        return False
    return any(rx.search(text) for rx in MARKER_RES)


def collect(day: dt.date):
    token = day_token(day)
    new_cards = sorted(WATCH.glob(f"*_{token}*"))
    new_cards = [f for f in new_cards if f.is_file()]
    intake = [f for f in new_cards if f.name.startswith("INTAKE_")]
    disp = [f for f in new_cards if is_dispositioned(f)]
    disp_set = set(disp)
    undispositioned = [f.name for f in new_cards if f not in disp_set]

    # Backlog touch: mtime on `day`, filename does NOT carry the date token.
    btouch = []
    day_start = dt.datetime.combine(day, dt.time.min).timestamp()
    day_end = day_start + 86400
    for f in WATCH.iterdir():
        if not f.is_file() or token in f.name:
            continue
        m = f.stat().st_mtime
        if day_start <= m < day_end:
            btouch.append(f)
    shelf = [f for f in WATCH.iterdir() if f.is_file()]
    return new_cards, intake, disp, undispositioned, btouch, shelf


def write_row(day: dt.date, note: str, new, intake, disp, undisp, btouch, shelf):
    led = _safe_ledger()
    date_iso = day.isoformat()
    gap = len(new) - len(disp)
    ratio = (len(disp) / len(new) * 100.0) if new else 0.0
    row = (f"| {date_iso} | {len(new)} | {len(intake)} | {len(disp)} | {gap} "
           f"| {ratio:.0f}% | {len(btouch)} | {len(shelf)} | {note or ''} |")
    colhead = ("| date | new | intake | disp | gap | disp% | btouch | shelf | note |\n"
               "|---|---|---|---|---|---|---|---|---|")

    if not led.exists():
        led.write_text(
            HEADER + "\n## Rows (one per day, latest run wins)\n\n" + colhead + "\n" + row + "\n",
            encoding="utf-8")
        return "created"

    lines = led.read_text(encoding="utf-8").splitlines()

    # Idempotent per day: replace existing row for this date, else append.
    out, replaced, have_table = [], False, False
    for line in lines:
        if line.startswith(f"| {date_iso} |"):
            if not replaced:
                out.append(row)
                replaced = True
            continue
        out.append(line)
        if line.startswith("| date | new |"):
            have_table = True
    if not replaced:
        if not have_table:
            out.append("")
            out.append(colhead)
        out.append(row)
    while out and not out[-1].strip():
        out.pop()
    led.write_text("\n".join(out) + "\n\n", encoding="utf-8")
    return "replaced" if replaced else "appended"


def main():
    ap = argparse.ArgumentParser(description="watch/ restock-vs-consumption ledger")
    ap.add_argument("--date", help="YYYYMMDD (default: today, local time)")
    ap.add_argument("--note", default="", help="free-text note for the row")
    args = ap.parse_args()

    if args.date:
        day = dt.datetime.strptime(args.date, "%Y%m%d").date()
    else:
        day = dt.date.today()

    new, intake, disp, undisp, btouch, shelf = collect(day)
    action = write_row(day, args.note, new, intake, disp, undisp, btouch, shelf)

    print(f"hunger ledger [{action}] {day.isoformat()}: "
          f"new={len(new)} intake={len(intake)} disp={len(disp)} "
          f"gap={len(new) - len(disp)} btouch={len(btouch)} shelf={len(shelf)}")
    print(f"ledger: {LEDGER}")
    if undisp:
        print("on the shelf (undispositioned):")
        for name in undisp:
            print(f"  - {name}")
    # Machine-readable echo for the trail.
    print(json.dumps({"date": day.isoformat(), "new": len(new),
                      "intake": len(intake), "disp": len(disp),
                      "gap": len(new) - len(disp), "btouch": len(btouch),
                      "shelf": len(shelf), "undispositioned": undisp,
                      "action": action}))


if __name__ == "__main__":
    sys.exit(main())
