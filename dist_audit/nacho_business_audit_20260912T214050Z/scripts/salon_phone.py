#!/usr/bin/env python3
"""salon_phone.py — drive AI web services on the headless android bodies.

Promises (operator order + ToS read, 2026-09-04):
  - runs our prompts/salons through services we already hold accounts on
  - harvests screenshots + UI-dump text to the dashboard gallery + intake queue
  - human cadence: jittered delays, per-service caps, bounded run windows
  - NEVER touches login/security/captcha flows — a challenge = skip, logged

Usage:
  python salon_phone.py --service zai --prompt-file auditor.txt
  python salon_phone.py --all --prompt-file pack.txt --max-per-service 3

Security note (Mimosa): every adb call below is a single inline
subprocess.run with a literal argv list and shell=False. Prompt text that
reaches the device passes through sanitize_for_device(), which strips every
character with shell meaning (adb shell joins argv into a device-side sh
command line; after sanitization nothing can break out of the `input text`
argument).
"""
import argparse, html, json, re, secrets, subprocess, time
from pathlib import Path

ADB = str(Path.home() / "AppData/Local/Android/Sdk/platform-tools/adb.exe")
SERIAL = "emulator-5554"
POCKET = "com.sovereign.pocketfleet/.MainActivity"
REPO = Path(r"C:\Users\foste\Documents\projects\local_sovereign_agent").resolve()
PROMPTS_DIR = REPO / "prompts"
GALLERY = REPO / "dashboard/static/phonesalon/runs"
QUEUE = REPO / "queue/phonesalon_runs.jsonl"
GALLERY.mkdir(parents=True, exist_ok=True)
PROMPTS_DIR.mkdir(parents=True, exist_ok=True)
RNG = secrets.SystemRandom()

SERVICES = {
    "zai":      "https://chat.z.ai",
    "deepseek": "https://chat.deepseek.com",
    "qwen":     "https://chat.qwen.ai",
    "grok":     "https://grok.com",
    "claude":   "https://claude.ai",
    "chatgpt":  "https://chatgpt.com",
}
CHROME_TEXTS = ("Generated by AI", "Terms of Service", "Privacy Policy",
                "Notifications", "Select a model", "Toggle Sidebar",
                "New Chat", "Sign in", "Chat History", "Send Message",
                "The current scenario cannot be cancelled", "Edit", "Copy",
                "Regenerate", "More", "Upload Files", "Deep Think")

def sanitize_for_device(text):
    """Allow only characters with no shell meaning: no ; | & $ ` \" ' \\ ! < > ~ * ? { }."""
    cleaned = re.sub(r"[^A-Za-z0-9 .,:!?()@#%\-/]", " ", text)
    return re.sub(r"\s+", "%s", cleaned.strip())  # adb: %s renders a space

def human_pause(lo=2.5, hi=7.0):
    time.sleep(RNG.uniform(lo, hi))

def load_prompt(rel):
    """Prompt files live under repo prompts/ only — traversal rejected."""
    p = (PROMPTS_DIR / rel).resolve()
    if PROMPTS_DIR.resolve() not in p.parents:
        raise SystemExit(f"prompt file escapes prompts/: {rel}")
    if not p.is_file():
        raise SystemExit(f"no such prompt file: {p}")
    return p.read_text(encoding="utf-8").strip()

def device_input_text(text):
    safe = sanitize_for_device(text)
    if safe:
        subprocess.run([ADB, "-s", SERIAL, "shell", "input", "text", safe],
                       capture_output=True, text=True, shell=False)

def device_tap(x, y):
    subprocess.run([ADB, "-s", SERIAL, "shell", "input", "tap", str(int(x)), str(int(y))],
                   capture_output=True, text=True, shell=False)

def device_keyevent(code):
    subprocess.run([ADB, "-s", SERIAL, "shell", "input", "keyevent", str(int(code))],
                   capture_output=True, text=True, shell=False)

def device_screenrecord_off():
    subprocess.run([ADB, "-s", SERIAL, "shell", "pkill", "-l2", "screenrecord"],
                   capture_output=True, text=True, shell=False)

def ui_dump():
    subprocess.run([ADB, "-s", SERIAL, "shell", "uiautomator", "dump", "/sdcard/ui.xml"],
                   capture_output=True, text=True, shell=False)
    r = subprocess.run([ADB, "-s", SERIAL, "exec-out", "cat", "/sdcard/ui.xml"],
                       capture_output=True, text=True, shell=False)
    return r.stdout or ""

def screen_nodes(raw):
    nodes = []
    for m in re.finditer(r"<node[^>]*>", raw):
        x = m.group(0)
        kind = (re.search(r'class="([^"]*)"', x) or [None, ""])[1].split(".")[-1]
        text = (re.search(r'text="([^"]*)"', x) or [None, ""])[1]
        desc = (re.search(r'content-desc="([^"]*)"', x) or [None, ""])[1]
        b = re.search(r'bounds="\[(\d+),(\d+)\]\[(\d+),(\d+)\]"', x)
        if not b:
            continue
        cx, cy = (int(b.group(1)) + int(b.group(3))) // 2, (int(b.group(2)) + int(b.group(4))) // 2
        nodes.append((kind, text, desc, (cx, cy)))
    return nodes

def login_state(raw):
    return "GUEST (Sign in visible)" if "Sign in" in raw else "LOGGED-IN?"

def harvest(service, tag):
    ts = time.strftime("%Y%m%dT%H%M%SZ", time.gmtime())
    png = GALLERY / f"{ts}_{service}_{tag}.png"
    r = subprocess.run([ADB, "-s", SERIAL, "exec-out", "screencap", "-p"],
                       capture_output=True, shell=False)
    png.write_bytes(r.stdout or b"")
    return png

def extract_answer(raw, prompt=""):
    marker = prompt[:30]
    out = []
    for (k, t, d, b) in screen_nodes(raw):
        if k in ("TextView", "View") and len(t) > 40:
            clean = html.unescape(t).strip()
            if marker and marker in clean:  # the input's own echo, not the answer
                continue
            if not any(c in clean for c in CHROME_TEXTS):
                out.append(clean)
    return "\n\n".join(out)

def open_service(url):
    subprocess.run([ADB, "-s", SERIAL, "shell", "am", "force-stop", "com.sovereign.pocketfleet"],
                   capture_output=True, text=True, shell=False)
    human_pause()
    subprocess.run([ADB, "-s", SERIAL, "shell", "am", "start", "-n", POCKET, "--es", "eu", url],
                   capture_output=True, text=True, shell=False)
    # load-wait poll: never trust fixed sleeps
    for _ in range(12):  # up to ~36s
        time.sleep(3)
        raw = ui_dump()
        if "Skip for now" in raw:  # login INTERSTITIAL — skip is the guest path,
            skip = [n for n in screen_nodes(raw) if n[1] == "Skip for now" or n[2] == "Skip for now"]
            if skip:
                device_tap(skip[0][3][0], skip[0][3][1])
                human_pause(4, 7)
        if [n for n in screen_nodes(ui_dump()) if n[0] == "EditText"]:
            return
        if "Sign in" in raw:  # page chrome loaded, just no field yet
            return

SEND_WORDS = ("Send Message", "Send", "Send prompt")

def find_send(raw):
    nodes = [n for n in screen_nodes(raw)
             if (n[1] in SEND_WORDS or n[2] in SEND_WORDS)]
    return nodes[0][3] if nodes else None

def type_prompt(prompt):
    for start in range(0, len(prompt), 160):
        device_input_text(prompt[start:start + 160])
        human_pause(1.2, 3.0)

def run_service(service, url, prompt, max_prompts):
    log = [f"[{service}] deep-link {url}"]
    open_service(url)
    raw = ui_dump()
    log.append(f"[{service}] state: {login_state(raw)}")
    if not [n for n in screen_nodes(raw) if n[0] == "EditText"]:
        log.append(f"[{service}] WALL: no input field — challenge or blocked. SKIP (never touch login flows).")
        harvest(service, "wall")
        return log
    for i in range(max_prompts):
        raw = ui_dump()
        edit = [n for n in screen_nodes(raw) if n[0] == "EditText"]
        if not edit:
            log.append(f"[{service}] input lost — stopping this service.")
            break
        cx, cy = edit[0][3]
        device_tap(cx, cy)
        human_pause()
        type_prompt(prompt)
        raw2 = ""
        spot = None
        for _ in range(4):  # keyboard settles; uiautomator can serve stale dumps while it animates
            human_pause(2.0, 3.5)
            raw2 = ui_dump()
            spot = find_send(raw2)
            if spot:
                break
        if spot is None:  # icon-only senders: any 'send' node in the input bar's y-band
            edit_y = edit[0][3][1]
            cands = [n for n in screen_nodes(raw2)
                     if "send" in (n[1] + " " + n[2]).lower() and n[3][1] > edit_y - 120]
            spot = cands[0][3] if cands else None
        sent = False
        for attempt in range(3):  # a tap is not a send until the input clears
            if spot:
                device_tap(spot[0], spot[1])
            else:
                device_keyevent(66)  # weak in some WebViews (newline only) — last resort
            human_pause(3, 5)
            now = [n for n in screen_nodes(ui_dump()) if n[0] == "EditText"]
            if not now or len(now[0][1].strip()) < 8:  # input cleared = send receipt
                sent = True
                break
            log.append(f"[{service}] send tap {attempt+1} unconfirmed; retrying")
        log.append(f"[{service}] prompt {i+1} {'sent' if sent else 'SEND UNCONFIRMED'}; polling")
        answer = ""
        for _ in range(8):  # up to ~4 min, jittered
            human_pause(20, 35)
            answer = extract_answer(ui_dump(), prompt)
            if answer:
                break
        png = harvest(service, f"p{i+1}")
        md = GALLERY / f"{time.strftime('%Y%m%dT%H%M%SZ', time.gmtime())}_{service}_p{i+1}.md"
        md.write_text(
            f"# {service} run p{i+1}\n\nstate: {login_state(ui_dump())}\n\n"
            f"## prompt\n\n{prompt}\n\n## answer (from UI tree)\n\n{answer or '(none captured — see png)'}\n",
            encoding="utf-8")
        log.append(f"[{service}] harvested {md.name} + {png.name}")
        device_keyevent(4)  # back toward new-chat doorway
        human_pause(8, 15)
    return log

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--service", choices=sorted(SERVICES))
    ap.add_argument("--all", action="store_true")
    ap.add_argument("--prompt-file", required=True)
    ap.add_argument("--max-per-service", type=int, default=2)
    args = ap.parse_args()
    if not args.service and not args.all:
        ap.error("pick --service X or --all")
    prompt = load_prompt(args.prompt_file)
    targets = list(SERVICES.items()) if args.all else [(args.service, SERVICES[args.service])]
    everything = []
    for svc, url in targets:
        everything += run_service(svc, url, prompt, args.max_per_service)
        human_pause(25, 60)  # between services — never burst
    print("\n".join(everything))
    with open(QUEUE, "a", encoding="utf-8") as f:
        f.write(json.dumps({"ts": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
                            "prompt_file": args.prompt_file, "log": everything}) + "\n")

if __name__ == "__main__":
    main()
