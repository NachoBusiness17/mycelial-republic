"""mag/boot_regen - the idempotent boot-surface regen chain behind context-pack.

R4 synthesis move 3 (2026-10-05,
watch/inbox/ractor_engine/2026-10-05-ouroboros-r4-memory/SYNTHESIS.md): organ
freshness was executed by siblings remembering to hand-run them, not by law -
all three organs (zknot LATEST, warm_state.json, rib_boot.json) were
regenerated by hand the same night the lenses were auditing them stale, and
censuses for the trigger behind them came back empty. This module is the
law-shaped fix: `mag.cmd context-pack` fires the chain BEFORE building the
pack, stamps every component's age into the pack header, and the CLI exits 2
when a step failed, a component is missing, or any component (including the
quantizer law pack the daily task owns) is older than the ONE decay bar.

Chain steps (all idempotent by their own design; rerunning writes the same
state):
  1. tools/zknot.py          -> memory/zknot/LATEST.md   (skips up-to-date
                                cards; exit 2 = the S1 no-silent-truncation
                                gate: the [:3] rewrite dropped qualifying
                                sessions unnamed)
  2. python -m mag.hermes_warm_boot -> memory/warm_state.json (rewrites)
  3. python -m mag.rib_boot          -> memory/rib_boot.json (rewrites; the
                                rib vault mount is read-only, no knot folded)

The law pack (memory/corpus/quantized_thought/compile_report.json) is NOT
recompiled here - the MagLawPackDaily scheduled task owns that - but its age
rides the same gate, so a dark task turns context-pack exit 2 within one
decay bar instead of hiding all compiled law behind a silent debt pointer.

MAG_BOOT_REGEN_SKIP=1 skips FIRING the steps (db locked, emergency) but never
skips the age gate: skipping the regen is allowed, serving stale organs is
not.
"""
from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
import time
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Callable

from config import ROOT
from mag.constants import PACK_STALE_DAYS

STEPS: tuple[tuple[str, str, float], ...] = (
    # name, producer invocation (after the interpreter), timeout_s
    ("zknot", (str(ROOT / "tools" / "zknot.py"),), 300.0),
    ("warm_boot", ("-m", "mag.hermes_warm_boot"), 180.0),
    ("rib_boot", ("-m", "mag.rib_boot"), 300.0),
)

ARTIFACTS: dict[str, Path] = {
    "zknot": ROOT / "memory" / "zknot" / "LATEST.md",
    "warm_boot": ROOT / "memory" / "warm_state.json",
    "rib_boot": ROOT / "memory" / "rib_boot.json",
    # the law pack is a read-only component here (daily task owns the write)
    "lawpack": ROOT / "memory" / "corpus" / "quantized_thought" / "compile_report.json",
}


def _age_days(path: Path, now: float | None = None) -> tuple[bool, float]:
    """Return (exists, age_in_days) for an artifact; lawpack ages by its own
    compiled stamp, the regen artifacts by mtime (they are rewritten whole)."""
    now = time.time() if now is None else now
    if not path.is_file():
        return False, float("inf")
    if path.name == "compile_report.json":
        try:
            ts = datetime.fromisoformat(
                json.loads(path.read_text(encoding="utf-8"))["compiled"]
                .replace("Z", "+00:00")).timestamp()
        except (OSError, ValueError, KeyError):
            return True, float("inf")  # unreadable stamp reads as infinitely old
        return True, max(0.0, (now - ts) / 86400.0)
    return True, max(0.0, (now - path.stat().st_mtime) / 86400.0)


def component_ages(now: float | None = None) -> dict[str, dict[str, Any]]:
    """Age stamp for every chain component (fired or read-only)."""
    out: dict[str, dict[str, Any]] = {}
    for name, path in ARTIFACTS.items():
        exists, age = _age_days(path, now)
        try:
            shown = path.relative_to(ROOT).as_posix()
        except ValueError:  # out-of-repo artifact (tests point ARTIFACTS at tmp)
            shown = path.as_posix()
        out[name] = {"path": shown, "exists": exists,
                     "age_d": (round(age, 3) if age != float("inf") else None)}
    return out


def _default_runner(cmd: list[str], timeout_s: float) -> tuple[int, str]:
    """Run one chain step under the SAME interpreter (mag.cmd guarantees the
    venv python; sys.executable IS it), windowless, bounded."""
    try:
        r = subprocess.run(
            [sys.executable, *cmd], cwd=str(ROOT), capture_output=True,
            text=True, encoding="utf-8", errors="replace", timeout=timeout_s,
            creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0))
        tail = ((r.stdout or "") + (r.stderr or ""))[-300:].strip()
        return int(r.returncode), tail
    except subprocess.TimeoutExpired:
        return 124, f"timeout after {timeout_s:.0f}s"
    except Exception as e:  # noqa: BLE001  (the chain must name failures, not crash)
        return 125, f"{type(e).__name__}: {e}"


def _verdict(report: dict[str, Any]) -> tuple[str, str]:
    for name, st in report["steps"].items():
        if not st["ok"]:
            return "step-failure", (f"{name} exited {st['exit']}"
                                    + (f": {st['tail']}" if st.get("tail") else ""))
    for name, a in report["ages"].items():
        if not a["exists"]:
            return "missing", f"{name} artifact missing at {a['path']}"
        if a["age_d"] is None or a["age_d"] > PACK_STALE_DAYS:
            return "age", (f"{name} is "
                           + ("unreadable" if a["age_d"] is None
                              else f"{a['age_d']:.1f}d old")
                           + f" (bar {PACK_STALE_DAYS:g}d)")
    if report.get("skipped"):
        return "skipped", "steps not fired (MAG_BOOT_REGEN_SKIP); age gate still enforced above"
    return "ok", "all components regenerated and fresh"


def run_boot_regen(
    *,
    runner: Callable[[list[str], float], tuple[int, str]] | None = None,
    now: float | None = None,
) -> dict[str, Any]:
    """Fire the chain once and return the report consumed by context-pack.

    verdict: ok | skipped | step-failure | missing | age. The CLI turns any
    verdict other than ok/skipped into exit 2; skipped still rides the age
    gate (missing/age verdicts fire regardless of whether steps ran).
    """
    runner = runner or _default_runner
    # R4b move 2 (2026-10-06, fold S3): attribution - every regen burst on
    # 2026-10-05/06 wrote zknot runs.jsonl rows with actor null / trigger
    # null because nothing carried the caller down to the organ. The chain
    # stamps itself: the zknot step rides --actor/--trigger so each receipt
    # row names who fired it; MAG_BOOT_REGEN_TRIGGER carries the caller
    # (the daily task sets MagBootRegenDaily, context-pack sets itself, a
    # hand crank reads manual).
    trigger = (os.environ.get("MAG_BOOT_REGEN_TRIGGER") or "").strip() or "manual"
    report: dict[str, Any] = {
        "schema": "mag_boot_regen.v1",
        "ts": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "bar_days": PACK_STALE_DAYS,
        "actor": "mag.boot_regen",
        "trigger": trigger,
        "steps": {},
        "skipped": False,
    }
    if os.environ.get("MAG_BOOT_REGEN_SKIP", "").strip() in ("1", "true", "yes", "on"):
        report["skipped"] = True
    else:
        for name, cmd, timeout_s in STEPS:
            t0 = time.monotonic()
            step_cmd = list(cmd)
            if name == "zknot":
                step_cmd += ["--actor", "mag.boot_regen", "--trigger", trigger]
            code, tail = runner(step_cmd, timeout_s)
            report["steps"][name] = {
                "ok": code == 0, "exit": code, "wall_s": round(time.monotonic() - t0, 2),
                "tail": tail,
            }
    # Ages AFTER firing: a step that wrote nothing leaves its artifact stale
    # and the age gate names it (or the step-failure verdict already did).
    report["ages"] = component_ages(now=now)
    report["verdict"], report["reason"] = _verdict(report)
    return report


def main(argv: list[str] | None = None) -> int:
    """CLI leg (R4b move 2, 2026-10-06): `python -m mag.boot_regen`.

    The clock leg the fold demanded (S2): regen was reader-coupled - the
    chain fired only inside `mag.cmd context-pack`, a command a seat must
    choose to run - so a dark week silently re-staled every organ with the
    alarm living inside the command the absent reader never ran. The
    MagBootRegenDaily scheduled task (scripts/boot_regen_daily.ps1,
    registered by scripts/register_boot_regen_task.ps1) fires this CLI on a
    clock; it enforces the SAME exit contract as the context-pack path
    (0 on ok/skipped, 2 on step-failure/missing/age), so a standalone run
    can never come back greener than the chained one.
    """
    ap = argparse.ArgumentParser(
        description="fire the boot-surface regen chain once (zknot LATEST + "
                    "warm_state.json + rib_boot.json) and gate on freshness")
    ap.add_argument("--json", action="store_true",
                    help="print the full report as JSON (the daily task's shape)")
    a = ap.parse_args(argv)
    rep = run_boot_regen()
    if a.json:
        print(json.dumps(rep, ensure_ascii=False, indent=1))
    else:
        print(f"BOOT REGEN verdict={rep['verdict']} trigger={rep.get('trigger')}")
        for name, st in rep["steps"].items():
            print(f"  step {name}: {'ok' if st['ok'] else 'FAIL'}"
                  f" exit={st['exit']} wall={st['wall_s']}s"
                  + (f" tail: {st['tail']}" if st.get("tail") else ""))
        for name, age in rep["ages"].items():
            shown = age["age_d"] if age["age_d"] is not None else "unreadable"
            print(f"  age {name}: {shown}d ({age['path']})")
        print(f"  {rep['reason']}")
    return 0 if rep["verdict"] in ("ok", "skipped") else 2


if __name__ == "__main__":
    raise SystemExit(main())
