"""CLI: python -m mag.keyrot {scan,rotate,ledger-verify}

scan    DRY-RUN always. Inventory -> policy -> plan. Writes state/keyrot/ reports and
        ledger events (detected, queued, planned_auto). No provider call, no store write.
rotate  Needs --apply AND --confirm <key_id> per key AND an interactive TTY. Runs the
        adapter, writes the owner-only store, optionally updates the consumer .env,
        then verifies the consumer with a timeout. Without --apply it only prints the plan.
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import os
import subprocess
import sys
from pathlib import Path

from mag.keyrot import inventory, ledger, policy, providers, store

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "state" / "keyrot"
STATUS = ROOT / "watch" / "inbox" / f"ESTATE_STATUS_{dt.date.today():%Y%m%d}.md"


def _plan(inv: dict, pol: dict) -> list[dict]:
    names = {n for r in inv.values() for n in r["env_names"]}
    rows = []
    for kid, r in sorted(inv.items()):
        fs = ledger.first_seen(kid) or r.get("first_seen_evidence") or dt.date.today().isoformat()
        r["first_seen"] = fs
        ev = policy.evaluate(r, fs, pol)
        prov = providers.by_name(r["type"])
        missing = [e for e in prov.mgmt_env if e not in os.environ and e not in names]
        if ev["action"] == "rotate":
            mode = "auto" if prov.api and r["type"] in providers.ADAPTERS and not missing else "manual"
        else:
            mode = "none"
        rows.append({**r, **ev, "mode": mode, "api_capable": prov.api, "mgmt_missing": missing,
                     "dashboard": prov.dashboard, "steps": prov.steps})
    return rows


def _queue_md(rows: list[dict]) -> str:
    out = [f"# keyrot manual queue {dt.date.today()}", "",
           "Generated by `python -m mag.keyrot scan` (DRY-RUN). key_id = type:sha256[:12]. No values.", ""]
    for r in rows:
        if r["mode"] != "manual" and r["action"] != "cleanup":
            continue
        out.append(f"## {r['key_id']} ({r['severity']}, {r['action']}) flags: {', '.join(r['flags'])}")
        out.append(f"- env: {', '.join(r['env_names'])}; locations: {len(r['locations'])}")
        for l in r["locations"]:
            out.append(f"  - {l}")
        out.append(f"- dashboard: {r['dashboard']}")
        for i, s in enumerate(r["steps"], 1):
            out.append(f"  {i}. {s}")
        if r["action"] == "rotate":
            out.append(f"  {len(r['steps'])+1}. Put new value in %LOCALAPPDATA%\\mag_secrets and every location above, then "
                       f"`python -m mag.keyrot rotate --mark-manual {r['key_id']}` (proposed) and verify consumer")
        if r["api_capable"] and r["mgmt_missing"]:
            out.append(f"- auto possible once management credential exists: {', '.join(r['mgmt_missing'])}")
        out.append("")
    return "\n".join(out)


def cmd_scan(a) -> int:
    pol = policy.load()
    inv, vals = inventory.collect()
    hist = inventory.enrich(inv, vals, workers=a.workers)
    vals.clear()
    rows = _plan(inv, pol)
    for r in rows:
        if ledger.first_seen(r["key_id"]) is None:
            ledger.append("detected", r["key_id"], mode="dry_run", type=r["type"], first_seen=r["first_seen"],
                          flags=r["flags"], locations=len(r["locations"]))
        want = {"auto": "planned_auto", "manual": "queued"}.get(r["mode"])
        if want and ledger.last_event(r["key_id"]) != want:
            ledger.append(want, r["key_id"], mode="dry_run", flags=r["flags"], dashboard=r["dashboard"])
    OUT.mkdir(parents=True, exist_ok=True)
    stamp = f"{dt.date.today():%Y%m%d}"
    (OUT / f"inventory_{stamp}.json").write_text(json.dumps(rows, indent=1), encoding="utf-8")
    (OUT / f"manual_queue_{stamp}.md").write_text(_queue_md(rows), encoding="utf-8")
    hints = inventory.audit_code_hints(STATUS)
    summary = {
        "mode": "DRY-RUN", "keys": len(rows),
        "rotate_auto": [r["key_id"] for r in rows if r["mode"] == "auto"],
        "rotate_manual": [r["key_id"] for r in rows if r["mode"] == "manual"],
        "cleanup": [r["key_id"] for r in rows if r["action"] == "cleanup"],
        "keep": [r["key_id"] for r in rows if r["action"] == "keep"],
        "audit_code_hints_to_check": [f"{f} {t}" for f, t in hints],
        "history_scan": hist, "store_acl": store.acl_ok(), "ledger": ledger.verify(),
        "consumer_verify_cmd": " ".join(pol["consumer_verify_cmd"]) + f" (timeout {pol['verify_timeout_s']}s)",
        "outputs": [f"state/keyrot/inventory_{stamp}.json", f"state/keyrot/manual_queue_{stamp}.md",
                    "state/keyrot/rotation_ledger.jsonl"],
    }
    (OUT / f"summary_{stamp}.json").write_text(json.dumps(summary, indent=1), encoding="utf-8")
    print(json.dumps(summary, indent=1))
    return 0


def _verify_consumer(pol: dict) -> tuple[bool, str]:
    try:
        r = subprocess.run(pol["consumer_verify_cmd"], capture_output=True, text=True, timeout=pol["verify_timeout_s"])
        ok = r.returncode == 0 and "ok" in r.stdout.lower()
        return ok, f"exit {r.returncode}"
    except (subprocess.TimeoutExpired, OSError) as e:
        return False, type(e).__name__


def cmd_rotate(a) -> int:
    pol = policy.load()
    stamp = f"{dt.date.today():%Y%m%d}"
    plan = json.loads((OUT / f"inventory_{stamp}.json").read_text(encoding="utf-8"))
    auto = {r["key_id"]: r for r in plan if r["mode"] == "auto"}
    if not a.apply:
        print(json.dumps({"mode": "DRY-RUN", "would_rotate": list(auto), "confirm_needed": "--apply --confirm <key_id>"}, indent=1))
        return 0
    if not (sys.stdin.isatty() and sys.stdout.isatty()) or os.environ.get("CURSOR_AGENT") or os.environ.get("GROK_AGENT"):
        print("refused: --apply needs an interactive operator TTY (secrets_policy non_interactive_always_deny)")
        return 2
    from tools.secret_guard.guard import _parse, _read
    inv, vals = inventory.collect()
    for path in [p for p, _ in inventory.candidate_files()]:  # management creds into process env only
        try:
            for k, v in _parse(str(path), _read(str(path))).items():
                if any(k == e for p in providers.P for e in p.mgmt_env):
                    os.environ.setdefault(k, v)
        except OSError:
            pass
    rc = 0
    for kid in a.confirm:
        if kid not in auto or kid not in vals:
            print(f"{kid}: not in today's auto plan or not found; skipped")
            continue
        r = auto[kid]
        env_name = r["env_names"][0]
        try:
            new, meta = providers.ADAPTERS[r["type"]](vals[kid], env_name)
        except Exception as e:  # noqa: BLE001
            print(f"{kid}: adapter failed {type(e).__name__}")
            rc = 1
            continue
        new_id = inventory.key_id(r["type"], new)
        ledger.append("rotated", kid, mode="apply", new_key_id=new_id, meta=meta)
        store.put(env_name, new)
        ledger.append("stored", new_id, mode="apply", store="%LOCALAPPDATA%\\mag_secrets", env=env_name)
        if a.update_consumer:
            store.update_consumer_env(Path(a.update_consumer), env_name, new)
        new = ""
        ok, why = _verify_consumer(pol)
        ledger.append("verified" if ok else "verify_failed", new_id, mode="apply", detail=why)
        print(f"{kid} -> {new_id}: {'verified' if ok else 'VERIFY FAILED ' + why}")
        rc |= 0 if ok else 1
    return rc


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="mag.keyrot")
    sp = ap.add_subparsers(dest="cmd", required=True)
    s = sp.add_parser("scan")
    s.add_argument("--workers", type=int, default=4)
    r = sp.add_parser("rotate")
    r.add_argument("--apply", action="store_true")
    r.add_argument("--confirm", action="append", default=[])
    r.add_argument("--update-consumer", help="path of consumer .env to update in place (backup to store)")
    sp.add_parser("ledger-verify")
    a = ap.parse_args(argv)
    if a.cmd == "scan":
        return cmd_scan(a)
    if a.cmd == "rotate":
        return cmd_rotate(a)
    print(json.dumps(ledger.verify()))
    return 0
