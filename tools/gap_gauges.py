#!/usr/bin/env python3
"""gap_gauges.py - the three-gap panel: what grows, what rots, what silence means
(lamplighter mate, 2026-10-06; commissioned by the gap sentinel's first reading,
12.59 GiB/day finding class, tools/gap_sentinel.py).

The sentinel meters estate growth and one watched sensor. Its first week of
readings asked for the next three gauges. This tool publishes all three in one
pass, from artifacts that already exist (no estate re-walk, no heavy IO):

  GROW/SHRINK (gauge 1): diff the last two snapshots in
  logs/gap_sentinel/history.jsonl. The sentinel flags growth over its bar but
  has no shrink gauge: the 2026-10-04T18:28Z -> 2026-10-05T13:19Z window shed
  -123.34 GiB (logs/gap_sentinel.log 2026-10-06 08:15 run) and no instrument
  flagged it (tools/rollup_delta.py, the shrink-aware meter, has run once ever,
  2026-09-30, logs/rollup_delta/run.log). This gauge flags growth over
  --growth-gib (default 1.0 GiB/day, the sentinel bar sized to the kpi.jsonl
  zero-reader class) and total shrink past --shrink-mib (default 512 MiB,
  deletion-event floor sized between rewrite noise and the growth bar). Windows
  under --min-window-days (default 0.25d) are evidence only, never a flag
  (census same-window law B2-215).

  ROT (gauge 2): the write-only class. Reads watch/inbox/ORPHAN_CENSUS.json
  (regenerated by tools/orphan_census.py) and logs/kpi.jsonl. The 2026-09-30
  census read registered_never_consumed 2,207 with 3 consume events ever; the
  2026-10-06 rerun read 3,381 with the same 3: the write-only class grew
  +1,174 (+53%) in 6.5 days while consumption stayed flat. Flags fire when
  never_consumed grew more than --rot-new (default 100) versus this gauge's
  prior history row while the consume total did not rise, and when
  logs/kpi.jsonl is unwritten for more than --stale-days (default 2.0d; the
  writer, mag/records.py write_kpi via `main.py summarize`, went dark
  2026-10-04T10:56Z and nothing alerted because the sentinel's watchlist held
  one sensor).

  SILENCE (gauge 3): sensor holes on a watchlist (add a row, get silence
  metering, the return-24 law). Watched by default: the x_radar sensor (the
  Sep 22-25 hole class), the KPI log, the dashboard rollup, its
  ROLLUP_DELTA metabolism panel (dark since 2026-09-30T09:32Z while rollup.json
  refreshes daily), and the census artifact itself (the 2026-10-09 lamplighter
  cycle found the rot input 3.0 days stale with no meter on it; CENSUS-DARK
  only sees absence, this row sees staleness, so a stale census may flag both
  CENSUS-DARK on absence and SENSOR-DARK/MISSING here). A sensor is flagged
  dark when its newest byte (mtime truth; the sentinel's freshness order,
  named in the verdict) is older than --stale-days, or SENSOR-MISSING. A
  missing census artifact is itself a silence finding (CENSUS-DARK):
  darkness is the thing this tool sees.

Fail-closed: an unparsable history row or census is exit 2, never a guess
(house law). First run with no prior gauge history is baseline for the rot
delta (evidence only, no flag). Alerts stay in the sentinel's lane: this tool
prints the panel and records history, it never writes memory/attention.md.

Exit codes: 0 = all gauges clean; 1 = any flag; 2 = cannot verify.
Usage: python tools/gap_gauges.py [--root PATH] [--growth-gib N] [--shrink-mib N]
[--rot-new N] [--stale-days N] [--min-window-days N] [--dry-run]
"""
from __future__ import annotations

import argparse
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

ESTATE_ROOT = Path(__file__).resolve().parent.parent

GIB = 1024 ** 3
MIB = 1024 ** 2
DEFAULT_GROWTH_GIB = 1.0
DEFAULT_SHRINK_MIB = 512.0
DEFAULT_ROT_NEW = 100
DEFAULT_STALE_DAYS = 2.0
DEFAULT_MIN_WINDOW_DAYS = 0.25

SENTINEL_HISTORY_RELPATH = "logs/gap_sentinel/history.jsonl"
CENSUS_RELPATH = "watch/inbox/ORPHAN_CENSUS.json"
KPI_RELPATH = "logs/kpi.jsonl"
HISTORY_RELPATH = "logs/gap_gauges/history.jsonl"
RUNLOG_RELPATH = "logs/gap_gauges/run.log"

SENSORS = (
    "dashboard/static/x_radar.json",
    "logs/kpi.jsonl",
    "dashboard/static/index_data/rollup.json",
    "dashboard/static/index_data/ROLLUP_DELTA.json",
    "watch/inbox/ORPHAN_CENSUS.json",
)


class GaugeError(Exception):
    """Cannot-verify condition; run() maps this to exit 2."""


def parse_iso(raw: str) -> datetime:
    """ISO-8601 to aware UTC datetime; GaugeError on garbage (fail-closed)."""
    try:
        stamp = datetime.fromisoformat(raw.replace("Z", "+00:00"))
    except (TypeError, ValueError) as exc:
        raise GaugeError(f"unparsable timestamp {raw!r}: {exc}") from exc
    if stamp.tzinfo is None:
        stamp = stamp.replace(tzinfo=timezone.utc)
    return stamp.astimezone(timezone.utc)


def load_sentinel_history(path: Path) -> list[dict]:
    """logs/gap_sentinel/history.jsonl oldest-first, ts_dt added. Missing file
    is a legitimate baseline (the sentinel's own law); an unparsable row is
    exit-2 disease."""
    if not path.is_file():
        return []
    rows: list[dict] = []
    for i, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        line = line.strip()
        if not line:
            continue
        try:
            row = json.loads(line)
        except json.JSONDecodeError as exc:
            raise GaugeError(f"sentinel history row {i} unparsable: {exc}") from exc
        if not isinstance(row.get("ts"), str) or not isinstance(row.get("projects"), dict):
            raise GaugeError(f"sentinel history row {i} is not the snapshot contract")
        row["ts_dt"] = parse_iso(row["ts"])
        rows.append(row)
    rows.sort(key=lambda r: r["ts_dt"])
    return rows


def load_census(path: Path) -> dict | None:
    """ORPHAN_CENSUS.json -> headline numbers; None when absent (CENSUS-DARK
    is a silence finding, not a crash). Unparsable = exit 2."""
    if not path.is_file():
        return None
    try:
        j = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise GaugeError(f"orphan census unparsable: {exc}") from exc
    counts = j.get("counts") if isinstance(j.get("counts"), dict) else {}
    return {
        "generated_at": j.get("generated_at") if isinstance(j.get("generated_at"), str) else None,
        "never_consumed": counts.get("registered_never_consumed")
        if isinstance(counts.get("registered_never_consumed"), int) else None,
        "consumed_total": len(j["consumed"]) if isinstance(j.get("consumed"), list) else None,
    }


def kpi_truth(path: Path) -> dict:
    """logs/kpi.jsonl bytes-truth: size, mtime age, last-row ts age. Tail read
    only: the file was 790 MB once (synthesis_agent.py:45) and a gauge that
    slurps it would be a new disease."""
    if not path.is_file():
        return {"missing": True, "size": None, "age_days": None, "last_row_ts": None}
    st = path.stat()
    last_ts = None
    with path.open("rb") as fh:
        fh.seek(0, 2)
        size = fh.tell()
        fh.seek(max(0, size - 65536))
        tail = fh.read().decode("utf-8", errors="replace")
    for line in reversed(tail.splitlines()):
        line = line.strip()
        if not line:
            continue
        try:
            row = json.loads(line)
        except json.JSONDecodeError:
            continue
        if isinstance(row.get("ts"), str):
            last_ts = row["ts"]
            break
    return {"missing": False, "size": size, "age_days": None, "last_row_ts": last_ts,
            "mtime": datetime.fromtimestamp(st.st_mtime, tz=timezone.utc)}


def sensor_age(path: Path, now: datetime, stale_days: float) -> dict:
    """mtime-truth freshness for one sensor (source named in the verdict, the
    sentinel's byte-truth honesty)."""
    if not path.is_file():
        return {"ok": False, "missing": True, "age_days": None}
    stamp = datetime.fromtimestamp(path.stat().st_mtime, tz=timezone.utc)
    age = (now - stamp).total_seconds() / 86400.0
    return {"ok": 0.0 <= age <= stale_days, "missing": False,
            "age_days": age, "stamp": stamp}


def gib(n: float) -> str:
    return f"{n / GIB:.2f} GiB"


def append_jsonl(path: Path, row: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("a", encoding="utf-8") as fh:
        fh.write(json.dumps(row, ensure_ascii=False) + "\n")


def load_own_history(path: Path) -> list[dict]:
    """This gauge's prior readings, oldest-first; unparsable = exit 2."""
    if not path.is_file():
        return []
    rows: list[dict] = []
    for i, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        line = line.strip()
        if not line:
            continue
        try:
            row = json.loads(line)
        except json.JSONDecodeError as exc:
            raise GaugeError(f"gap_gauges history row {i} unparsable: {exc}") from exc
        rows.append(row)
    return rows


def run(root: Path, growth_bytes: float = DEFAULT_GROWTH_GIB * GIB,
        shrink_bytes: float = DEFAULT_SHRINK_MIB * MIB, rot_new: int = DEFAULT_ROT_NEW,
        stale_days: float = DEFAULT_STALE_DAYS, min_window_days: float = DEFAULT_MIN_WINDOW_DAYS,
        dry_run: bool = False, now: datetime | None = None) -> int:
    """One panel pass. Returns the exit code (0 clean, 1 flags, 2 cannot verify)."""
    now = now or datetime.now(timezone.utc)
    flags: list[str] = []

    try:
        sent = load_sentinel_history(root / SENTINEL_HISTORY_RELPATH)
        census = load_census(root / CENSUS_RELPATH)
        own = load_own_history(root / HISTORY_RELPATH)
    except GaugeError as exc:
        print(f"GAP-GAUGES: cannot verify, {exc}")
        return 2

    # Gauge 1: GROW/SHRINK over the sentinel's last two snapshots.
    growth_panel: dict = {"window": None, "total_delta": None, "top_grow": [], "top_shrink": []}
    if len(sent) < 2:
        print(f"GAP-GAUGES: grow baseline - {len(sent)} sentinel snapshot(s) on file, "
              "diffs start at two")
    else:
        prev, cur = sent[-2], sent[-1]
        days = (cur["ts_dt"] - prev["ts_dt"]).total_seconds() / 86400.0
        names = sorted(set(prev["projects"]) | set(cur["projects"]))
        rows = []
        for name in names:
            delta = cur["projects"].get(name, 0) - prev["projects"].get(name, 0)
            rows.append((name, delta))
        rows.sort(key=lambda r: -r[1])
        total = cur.get("total_bytes", 0) - prev.get("total_bytes", 0)
        growth_panel = {
            "window": {"prev": prev["ts"], "cur": cur["ts"], "days": round(days, 4)},
            "total_delta": total,
            "top_grow": rows[:3], "top_shrink": list(reversed(rows[-3:])),
        }
        head = (f"window {prev['ts']} -> {cur['ts']} ({days:.2f}d), total {gib(total)}")
        if days < min_window_days:
            print(f"GAP-GAUGES: grow evidence only - window under {min_window_days}d, "
                  f"no flag: {head}")
        else:
            if total / days > growth_bytes:
                flags.append(f"GROW total {gib(total)} ({gib(total / days)}/day) in {head}")
            if total < 0 and abs(total) > shrink_bytes:
                flags.append(f"SHRINK total {gib(total)} ({gib(abs(total) / days)}/day out) "
                             f"in {head}")
            if not flags:
                print(f"GAP-GAUGES: grow clean - {head}")
            for label, picks in (("grow", rows[:3]), ("shrink", list(reversed(rows[-3:])))):
                for name, delta in picks:
                    if delta != 0:
                        print(f"  {label}: {name} {gib(delta)}")

    # Gauge 2: ROT from the orphan census + the KPI log.
    rot_panel: dict = {"census": None, "kpi": None}
    if census is None:
        flags.append(f"CENSUS-DARK {CENSUS_RELPATH} absent (the rot instrument itself is dark)")
        print(f"GAP-GAUGES: rot - census artifact missing: {CENSUS_RELPATH}")
    else:
        prev_row = next((r for r in reversed(own)
                         if isinstance(r.get("census_never_consumed"), int)), None)
        nc, ct = census["never_consumed"], census["consumed_total"]
        line = (f"census {census['generated_at']}: never_consumed {nc}, "
                f"consumed_ever {ct}")
        if prev_row is None:
            print(f"GAP-GAUGES: rot baseline - no prior gauge reading to delta, {line}")
        else:
            d_nc = (nc or 0) - prev_row["census_never_consumed"]
            d_ct = (ct or 0) - (prev_row.get("census_consumed_total") or 0)
            line += f" (delta never_consumed {d_nc:+d}, consumed {d_ct:+d} since gauge history)"
            if d_nc > rot_new and d_ct <= 0:
                flags.append(f"ROT never_consumed {prev_row['census_never_consumed']} -> {nc} "
                             f"(+{d_nc}, bar {rot_new}) with consumed flat at {ct}")
            elif d_nc <= rot_new:
                print(f"GAP-GAUGES: rot clean - {line}")
            else:
                print(f"GAP-GAUGES: rot grew {d_nc:+d} but consumption moved {d_ct:+d}: {line}")
        rot_panel["census"] = census
    kpi = kpi_truth(root / KPI_RELPATH)
    if kpi["missing"]:
        flags.append(f"KPI-MISSING {KPI_RELPATH} absent")
    else:
        age = (now - kpi["mtime"]).total_seconds() / 86400.0
        kpi["age_days"] = round(age, 3)
        rot_panel["kpi"] = {k: kpi[k] for k in ("size", "age_days", "last_row_ts")}
        if age > stale_days:
            flags.append(f"KPI-DARK {KPI_RELPATH} unwritten {age:.2f}d (bar {stale_days}d), "
                         f"last row ts {kpi['last_row_ts']}")
        else:
            print(f"GAP-GAUGES: kpi fresh - {kpi['size']} bytes, last row {kpi['last_row_ts']}")

    # Gauge 3: SILENCE over the sensor watchlist.
    silence_panel: list[dict] = []
    for rel in SENSORS:
        fr = sensor_age(root / rel, now, stale_days)
        if fr["ok"]:
            print(f"GAP-GAUGES: sensor {rel} fresh (mtime age {fr['age_days']:.2f}d "
                  f"of {stale_days}d bar)")
        elif fr["missing"]:
            flags.append(f"SENSOR-MISSING {rel}")
            print(f"GAP-GAUGES: SENSOR-MISSING {rel}")
        else:
            flags.append(f"SENSOR-DARK {rel} mtime age {fr['age_days']:.2f}d "
                         f"(bar {stale_days}d)")
            print(f"GAP-GAUGES: SENSOR-DARK {rel} mtime age {fr['age_days']:.2f}d")
        silence_panel.append({k: (v.isoformat() if isinstance(v, datetime) else v)
                              for k, v in fr.items()} | {"sensor": rel})

    print(f"GAP-GAUGES: {len(flags)} flag(s)")
    for f in flags:
        print(f"  FLAG {f}")

    if not dry_run:
        append_jsonl(root / HISTORY_RELPATH, {
            "ts": now.isoformat(),
            "census_never_consumed": (census or {}).get("never_consumed"),
            "census_consumed_total": (census or {}).get("consumed_total"),
            "kpi_last_row_ts": kpi.get("last_row_ts") if not kpi["missing"] else None,
            "growth": growth_panel, "rot": rot_panel, "silence": silence_panel,
            "flags": flags,
        })
        append_jsonl(root / RUNLOG_RELPATH, {"ts": now.isoformat(),
                                             "exit": 1 if flags else 0, "flags": flags})
    return 1 if flags else 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="three-gap panel: grow, rot, silence")
    parser.add_argument("--root", type=Path, default=ESTATE_ROOT)
    parser.add_argument("--growth-gib", type=float, default=DEFAULT_GROWTH_GIB)
    parser.add_argument("--shrink-mib", type=float, default=DEFAULT_SHRINK_MIB)
    parser.add_argument("--rot-new", type=int, default=DEFAULT_ROT_NEW)
    parser.add_argument("--stale-days", type=float, default=DEFAULT_STALE_DAYS)
    parser.add_argument("--min-window-days", type=float, default=DEFAULT_MIN_WINDOW_DAYS)
    parser.add_argument("--dry-run", action="store_true",
                        help="print the panel only; no history row, no run.log")
    args = parser.parse_args(argv)
    return run(args.root.resolve(), growth_bytes=args.growth_gib * GIB,
               shrink_bytes=args.shrink_mib * MIB, rot_new=args.rot_new,
               stale_days=args.stale_days, min_window_days=args.min_window_days,
               dry_run=args.dry_run)


if __name__ == "__main__":
    sys.exit(main())
