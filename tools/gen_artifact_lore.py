def no_dash(text: str) -> str:
    if EM_DASH.search(text):
        raise SystemExit(f"em-dash law violation in generated output: {text!r}")
    return text


def join_mine() -> dict[tuple[str, str], str]:
    """(english, pos) -> dwarven word; every key must resolve to ONE word."""
    entries = json.loads(MINE.read_text(encoding="utf-8"))["dwarf"]
    hits: dict[tuple[str, str], set[str]] = {}
    for e in entries:
        hits.setdefault((e["english"], e["pos"]), set()).add(e["word"])
    words: dict[tuple[str, str], str] = {}
    for key in NOUN_KEYS + ADJ_KEYS:
        found = hits.get(key)
        if not found:
            raise SystemExit(f"ungrounded fold key (not in mine): {key}")
        if len(found) > 1:
            raise SystemExit(f"ambiguous fold key {key}: mine holds {sorted(found)}")
        words[key] = next(iter(found))
    return words


def gen_region(words: dict[tuple[str, str], str]) -> str:
    """The generated region in LF; caller converts to the file's EOL."""
    lines = [BEGIN, REGEN, "local DWARVEN: { Word } = {"]
    for key in NOUN_KEYS + ADJ_KEYS:
        gloss, pos = key
        lines.append(f'\t{{ gloss = "{gloss}", dw = "{words[key]}", pos = "{pos}" }},')
    lines.append("}")
    lines.append(END)
    return "\n".join(lines)


def splice(text: str, region_lf: str) -> str:
    eol = "\r\n" if "\r\n" in text else "\n"
    region = region_lf.replace("\n", eol)
    begin_at = text.find(BEGIN)
    end_at = text.find(END)
    if (begin_at == -1) != (end_at == -1):
        raise SystemExit("marker corruption: only one of BEGIN/END present")
    if begin_at != -1:
        return text[:begin_at] + region + text[end_at + len(END):]
    # first run: wrap the existing hand-folded DWARVEN block with markers
    # (\r? because this CRLF file's lines end \r\n and re.M `$` will not
    # match before the \r)
    start = re.search(r"^local DWARVEN: \{ Word \} = \{\r?$", text, re.M)
    if not start:
        raise SystemExit("no BEGIN/END markers and no `local DWARVEN` block found")
    close = re.search(r"^\}\r?\n", text[start.end():], re.M)
    if not close:
        raise SystemExit("DWARVEN block has no closing `}` line")
    # consume the close's full newline: stopping at `$` would strand the \r
    # and rewrite that line ending to bare LF (caught by EOL census in t26)
    stop = start.end() + close.end()
    return text[:start.start()] + region + text[stop:]


def main() -> int:
    words = join_mine()
    # the generated region is the only text this tool authors: it must carry
    # no em-dash. Pre-existing dashes elsewhere in the module (header comment,
    # moodLine) are outside the markers and stay untouched, per gala t4.
    region = no_dash(gen_region(words))
    # read bytes and decode by hand: read_text() would translate the file's
    # CRLF to LF before the EOL detection below could see it, and the splice
    # would silently rewrite every line ending in the module.
    text = TARGET.read_bytes().decode("utf-8")
    out = splice(text, region)
    if out != text:
        TARGET.write_bytes(out.encode("utf-8"))
        print(f"spliced generated region into {TARGET}")
    else:
        print(f"{TARGET} already up to date (byte-identical rerun)")
    n_noun, n_adj = len(NOUN_KEYS), len(ADJ_KEYS)
    print(f"DWARVEN pool: {n_noun} nouns + {n_adj} adjectives = {n_noun + n_adj} entries, all joined from df_lexicon_full.json")
    return 0


if __name__ == "__main__":
    sys.exit(main())
