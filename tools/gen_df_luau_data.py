#!/usr/bin/env python3
"""Generate the DF-mined Luau data modules for THE MOUNTAIN's roblox build.

Emits (byte-identical on rerun, sorted keys where dicts are emitted):
  roblox/src/shared/DfGoods.luau       -- tradegoods + material values + quality ladder
  roblox/src/shared/RcpData.luau       -- 235 weighted creature profiles + attack classes
                                          + uniform body materials
  roblox/src/shared/SphereKinship.luau -- derived sphere kinship graph (alignment +
                                          co-occurrence allies, class opposition)
  roblox/src/shared/RegionSpheres.luau -- generator_region_spheres verbatim
                                          (region kinship rows, zone-alliance gate)

Sources (READ ONLY mine, corpus/df_mine/):
  df_economy.json     tradegoods[].good/class/base/material_value/unit_value,
                      material_values.metals_INORGANIC, material_values.gems
  df_procedural.json  creature_profiles[235], attack_tweaks, uniform_body_materials
  df_spheres.json     spheres[130], good_spheres, evil_spheres,
                      generator_region_spheres, by_creature

The quality ladder is ENGINE-side (not in raws); sourced from
dwarffortresswiki.org/Item value (fetched 2026-09-25), embedded here as
constants so both sides of the formula carry their provenance.

Law: never hand-copy mined rows; regenerate. Run:
  .venv/Scripts/python.exe tools/gen_df_luau_data.py
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MINE = ROOT / "corpus" / "df_mine"
OUT_SHARED = ROOT / "roblox" / "src" / "shared"

EM_DASH = re.compile(r"[\u2010\u2011\u2012\u2013\u2014\u2015]")

HEADER = "--!strict\n-- GENERATED by tools/gen_df_luau_data.py from corpus/df_mine/ -- do not hand-edit.\n-- Regenerate: .venv/Scripts/python.exe tools/gen_df_luau_data.py\n"


def no_dash(text: str) -> str:
    if EM_DASH.search(text):
        raise SystemExit(f"em-dash law violation in generated output: {text!r}")
    return text


def luau_str(s: str) -> str:
    return '"' + no_dash(s).replace("\\", "\\\\").replace('"', '\\"') + '"'


def luau_num(n) -> str:
    return str(int(n))


def luau_key(s: str) -> str:
    # bracketed string key: Luau table constructors need ["K"] = v
    return "[" + luau_str(s) + "]"


def dump_dict_str_num(name: str, d: dict, comment: str) -> str:
    lines = [f"-- {comment}", f"{name} = {{"]
    for k in sorted(d):
        lines.append(f"\t{luau_key(k)} = {luau_num(d[k])},")
    lines.append("}")
    return "\n".join(lines)


def dump_array_of_tables(name: str, rows: list[dict], fields: list[tuple[str, str]], comment: str) -> str:
    """fields: (json_key, luau_key) pairs; values str or int."""
    lines = [f"-- {comment}", f"{name} = {{"]
    for r in rows:
        cells = []
        for jk, lk in fields:
            v = r[jk]
            cells.append(f"{lk} = {luau_str(v) if isinstance(v, str) else luau_num(v)}")
        lines.append("\t{ " + ", ".join(cells) + " },")
    lines.append("}")
    return "\n".join(lines)


def gen_dfgoods(econ: dict) -> str:
    raw_goods = econ["tradegoods"]
    # some mined rows are material-only notes (dyes, cloth, parchment material):
    # no base to multiply, so they are not goods rows; base may arrive as
    # raws_value_token on TOOL rows instead of base. Skips are logged, not silent.
    goods = []
    skipped = []
    for g in raw_goods:
        base = g.get("base", g.get("raws_value_token"))
        mv = g.get("material_value")
        if base is None or not isinstance(mv, int) or not isinstance(g.get("unit_value"), int):
            # material-only notes (dyes, cloth) and formula-note rows where mv or
            # unit is a phrase ("varies (cover)", "sum of ingredient values"):
            # no computable base x mv, so they are not goods rows. Logged, not silent.
            skipped.append(g["good"])
            continue
        goods.append({**g, "base": base, "mv": mv})
    if skipped:
        print(f"skipped (no computable base x mv): {skipped}")
    metals = econ["material_values"]["metals_INORGANIC"]
    mats = dict(metals)
    mats["PARCHMENT"] = 10  # the only non-1 material template (raws-verified)
    mats.update(
        CLEAR_DIAMOND=60,
        TSAVORITE=30,
        INDIGO_TOURMALINE=25,
        CLEAR_ZIRCON=25,
    )
    # engine-side quality ladder (dwarffortresswiki.org Item value, 2026-09-25)
    quality = [
        ("well-crafted", 1.1, 3),
        ("finely crafted", 1.2, 6),
        ("superior", 1.33, 10),
        ("exceptional", 1.5, 15),
        ("masterful", 2, 30),
    ]
    out = [HEADER]
    out.append("-- Fold: DF value formula into the Exchange (WORLDGEN_MINE.md THE OWED).\n")
    out.append("-- value = BASE x MATERIAL_VALUE x QUALITY_MULT + QUALITY_BONUS; artifact x20 +300.\n")
    out.append(dump_dict_str_num("DfGoods.MATERIALS", mats, "raws-verified MATERIAL_VALUE (metals_INORGANIC + parchment + top gems)"))
    out.append("")
    out.append(
        dump_array_of_tables(
            "DfGoods.GOODS",
            [
                {
                    "good": g["good"],
                    "class": g["class"],
                    "base": g["base"],
                    "mv": g["material_value"],
                    "unit": g["unit_value"],
                }
                for g in goods
            ],
            [("good", "good"), ("class", "class"), ("base", "base"), ("mv", "mv"), ("unit", "unit")],
            "tradegoods: base x mv = unit (the mined table cross-checks the formula)",
        )
    )
    out.append("")
    lines = ["-- engine-side quality ladder (wiki Item value, fetched 2026-09-25)", "DfGoods.QUALITY = {"]
    for qname, mult, bonus in quality:
        lines.append(f'\t{{ name = {luau_str(qname)}, mult = {mult}, bonus = {bonus} }},')
    lines.append("}")
    out.append("\n".join(lines))
    out.append("")
    out.append('return DfGoods\n')
    # wrap: the tables must live inside the returned table; emit via a builder
    body = "\n".join(out)
    body = body.replace("DfGoods.MATERIALS = {", "local MATERIALS = {")
    body = body.replace("DfGoods.GOODS = {", "local GOODS = {")
    body = body.replace("DfGoods.QUALITY = {", "local QUALITY = {")
    tail = "\nlocal DfGoods = {}\nDfGoods.MATERIALS = MATERIALS\nDfGoods.GOODS = GOODS\nDfGoods.QUALITY = QUALITY\n"
    body = body.replace("\nreturn DfGoods\n", "\n" + tail + "\nreturn DfGoods\n")
    return body


def gen_rcpdata(proc: dict) -> str:
    profiles = proc["creature_profiles"]
    attacks = proc["attack_tweaks"]
    ubm = proc["uniform_body_materials"]
    out = [HEADER]
    out.append("-- Fold: procedural FB bodies into the wisps (WORLDGEN_MINE.md THE OWED).\n")
    out.append(
        dump_array_of_tables(
            "RcpData.PROFILES",
            [
                {
                    "type": p["type"],
                    "name": p["name"],
                    "bodyBase": p["body_base"],
                    "class": p["c_class"],
                    "weight": p["weight"],
                    "flags": ";".join(p["flags"]),
                }
                for p in profiles
            ],
            [("type", "type"), ("name", "name"), ("bodyBase", "bodyBase"), ("class", "class"), ("weight", "weight"), ("flags", "flags")],
            "235 weighted RCP profiles; flags joined on ';' (must_have_*, cannot_have_*, digits)",
        )
    )
    out.append("")
    lines = ["-- attack classes: trigger + the DF announcement warning"]
    lines.append("RcpData.ATTACKS = {")
    for k in sorted(attacks):
        if k.startswith("_"):
            continue
        v = attacks[k]
        trig = v.get("trigger", "rolled")
        warn = v.get("warning", "Beware its attack!")
        lines.append(f"\t{luau_key(k)} = {{ trigger = {luau_str(trig)}, warning = {luau_str(warn)} }},")
    lines.append("}")
    out.append("\n".join(lines))
    out.append("")
    matter = sorted(ubm["matter"].keys())
    out.append("RcpData.MATTER = { " + ", ".join(luau_str(m) for m in matter) + " }")
    out.append("")
    insub = sorted(ubm["insubstantial_set"])
    out.append("RcpData.INSUBSTANTIAL = { " + ", ".join(luau_str(m) for m in insub) + " }")
    out.append("")
    lines = ["-- sphere -> allowed uniform material (mined map)"]
    lines.append("RcpData.SPHERE_MATERIAL = {")
    for sphere in sorted(ubm["sphere_material_map"]):
        mats = ubm["sphere_material_map"][sphere]
        lines.append(f"\t{luau_key(sphere)} = {{ {', '.join(luau_str(m) for m in sorted(mats))} }},")
    lines.append("}")
    out.append("\n".join(lines))
    out.append("")
    out.append("local RcpData = {}\nRcpData.PROFILES = PROFILES\nRcpData.ATTACKS = ATTACKS\nRcpData.MATTER = MATTER\nRcpData.INSUBSTANTIAL = INSUBSTANTIAL\nRcpData.SPHERE_MATERIAL = SPHERE_MATERIAL\n\nreturn RcpData\n")
    body = "\n".join(out)
    for t in ("PROFILES", "ATTACKS", "MATTER", "INSUBSTANTIAL", "SPHERE_MATERIAL"):
        body = body.replace(f"RcpData.{t} = ", f"local {t} = ", 1)
        # fix the definitions only (the tail assignments come after)
        idx_def = body.find(f"local {t} = ")
        idx_tail = body.find(f"RcpData.{t} = {t}")
        if idx_tail == -1:
            raise SystemExit(f"tail assignment missing for {t}")
    return body


def gen_sphere_kinship(sph: dict) -> str:
    """Derive the sphere kinship graph from the mine's own sourced fields.

    No authored edges: allies/opposed are computed, not written by hand.
      alignment = good_spheres / evil_spheres classes
      allies    = same-class peers + co-occurrence in one generator region
                  (generator_region_spheres) or on one named creature
                  (by_creature)
      opposed   = every sphere of the opposite class
      unaligned = no enmity (OPPOSED = {} is a fact, not an omit)
    Opposition wins over co-occurrence when a pair lands in both.
    """
    spheres: list[str] = sph["spheres"]
    known = set(spheres)
    good = set(sph["good_spheres"])
    evil = set(sph["evil_spheres"])
    for name, cls in (("good_spheres", good), ("evil_spheres", evil)):
        unknown = cls - known
        if unknown:
            raise SystemExit(f"{name} lists spheres outside the 130: {sorted(unknown)}")
        if good & evil:
            raise SystemExit(f"alignment clash: {sorted(good & evil)}")

    allies: dict[str, set[str]] = {s: set() for s in spheres}

    def add_cooccurrence(group: str, members: list[str]) -> None:
        for a in members:
            for b in members:
                if a != b:
                    allies[a].add(b)

    for cls in (good, evil):
        add_cooccurrence("alignment class", sorted(cls))
    for region, members in sph["generator_region_spheres"].items():
        unknown = set(members) - known
        if unknown:
            raise SystemExit(f"generator_region_spheres[{region}] outside the 130: {sorted(unknown)}")
        add_cooccurrence(f"region {region}", members)
    for creature, members in sph["by_creature"].items():
        unknown = set(members) - known
        if unknown:
            raise SystemExit(f"by_creature[{creature}] outside the 130: {sorted(unknown)}")
        add_cooccurrence(f"creature {creature}", members)

    opposed: dict[str, set[str]] = {}
    for s in spheres:
        if s in good:
            opposed[s] = set(evil)
        elif s in evil:
            opposed[s] = set(good)
        else:
            opposed[s] = set()  # unaligned: no enmity, stated not omitted
        # precedence law: good and evil never ally, so a co-occurrence edge
        # that crosses the alignment split is dropped from ALLIES
        allies[s] -= opposed[s]
        if not allies[s] and opposed[s]:
            raise SystemExit(f"{s} lost every ally while opposed: graph hole")

    out = [HEADER]
    out.append("-- Fold: sphere kinship graph -> zone alliances (WORLDGEN_MINE.md law 4).")
    out.append("-- Derived from df_spheres.json sourced fields, never authored:")
    out.append("--   alignment = good_spheres / evil_spheres classes;")
    out.append("--   allies = same-class peers + co-occurrence in one generator region")
    out.append("--     (generator_region_spheres) or on one named creature (by_creature);")
    out.append("--   opposed = every sphere of the opposite class; unaligned spheres carry")
    out.append("--     no enmity (empty lists are facts, not omissions). Opposition wins")
    out.append("--     over co-occurrence when a pair lands in both.")
    out.append("")
    out.append("local ALIGNMENT = {")
    for s in sorted(good | evil):
        out.append(f"\t{luau_key(s)} = {luau_str('good' if s in good else 'evil')},")
    out.append("}")
    out.append("")
    out.append("local ALLIES = {")
    for s in spheres:
        out.append(f"\t{luau_key(s)} = {{ {', '.join(luau_str(a) for a in sorted(allies[s]))} }},")
    out.append("}")
    out.append("")
    out.append("local OPPOSED = {")
    for s in spheres:
        out.append(f"\t{luau_key(s)} = {{ {', '.join(luau_str(o) for o in sorted(opposed[s]))} }},")
    out.append("}")
    out.append("")
    out.append("local SphereKinship = {}\n")
    out.append("SphereKinship.ALIGNMENT = ALIGNMENT\n")
    out.append("SphereKinship.ALLIES = ALLIES\n")
    out.append("SphereKinship.OPPOSED = OPPOSED\n")
    out.append(f"SphereKinship.COUNT = {luau_num(len(spheres))}\n")
    out.append("\nreturn SphereKinship\n")
    body = "\n".join(out)
    stats = {
        "spheres": len(spheres),
        "good": len(good),
        "evil": len(evil),
        "ally_edges": sum(len(v) for v in allies.values()),
        "opposed_edges": sum(len(v) for v in opposed.values()),
        "ally_empty": sum(1 for v in allies.values() if not v),
        "opposed_empty": sum(1 for v in opposed.values() if not v),
    }
    return body, stats


def gen_region_spheres(sph: dict) -> str:
    """generator_region_spheres verbatim: the sourced rows the zone-alliance
    gate joins to (WORLDGEN_MINE.md law 4, t35).

    No authored data lands here: each WAVE row picks one of these region
    keys as its strict-required `region` field in server/init.server.luau
    (t67: ZoneGate receives the join derived at init, it owns no zone
    list), and that join is authored because zone names are the estate's
    own and exist nowhere in the mine. Region keys
    are sorted for deterministic output; member order stays verbatim.
    """
    regions: dict[str, list[str]] = sph["generator_region_spheres"]
    known = set(sph["spheres"])
    out = [HEADER]
    out.append("-- Fold: region kinship rows -> zone alliances (WORLDGEN_MINE.md law 4).")
    out.append("-- generator_region_spheres verbatim from df_spheres.json: sourced,")
    out.append("-- never authored. NONE = no spheres: an empty row is a fact, and a")
    out.append("-- zone joined to it would carry no gate.")
    out.append("")
    out.append("local REGION_SPHERES = {")
    for region in sorted(regions):
        unknown = set(regions[region]) - known
        if unknown:
            raise SystemExit(f"generator_region_spheres[{region}] outside the 130: {sorted(unknown)}")
        out.append(f"\t{luau_key(region)} = {{ {', '.join(luau_str(m) for m in regions[region])} }},")
    out.append("}")
    out.append("")
    out.append("local RegionSpheres = {}\n")
    out.append("RegionSpheres.REGION_SPHERES = REGION_SPHERES\n")
    out.append(f"RegionSpheres.COUNT = {luau_num(len(regions))}\n")
    out.append("\nreturn RegionSpheres\n")
    return "\n".join(out)


def main() -> int:
    econ = json.loads((MINE / "df_economy.json").read_text(encoding="utf-8"))
    proc = json.loads((MINE / "df_procedural.json").read_text(encoding="utf-8"))
    sph = json.loads((MINE / "df_spheres.json").read_text(encoding="utf-8"))
    OUT_SHARED.mkdir(parents=True, exist_ok=True)

    goods_luau = gen_dfgoods(econ)
    rcp_luau = gen_rcpdata(proc)
    kin_luau, kin_stats = gen_sphere_kinship(sph)
    region_luau = gen_region_spheres(sph)
    no_dash(goods_luau)
    no_dash(rcp_luau)
    no_dash(kin_luau)
    no_dash(region_luau)

    (OUT_SHARED / "DfGoods.luau").write_text(goods_luau, encoding="utf-8", newline="\n")
    (OUT_SHARED / "RcpData.luau").write_text(rcp_luau, encoding="utf-8", newline="\n")
    (OUT_SHARED / "SphereKinship.luau").write_text(kin_luau, encoding="utf-8", newline="\n")
    (OUT_SHARED / "RegionSpheres.luau").write_text(region_luau, encoding="utf-8", newline="\n")
    print(f"wrote {OUT_SHARED / 'DfGoods.luau'} ({len(goods_luau)} bytes)")
    print(f"wrote {OUT_SHARED / 'RcpData.luau'} ({len(rcp_luau)} bytes)")
    print(f"wrote {OUT_SHARED / 'SphereKinship.luau'} ({len(kin_luau)} bytes)")
    print(f"wrote {OUT_SHARED / 'RegionSpheres.luau'} ({len(region_luau)} bytes)")
    print(f"goods rows: {len(econ['tradegoods'])}, profiles: {len(proc['creature_profiles'])}, "
          f"regions: {len(sph['generator_region_spheres'])}")
    print(
        "kinship: spheres {spheres}, aligned good/evil {good}/{evil}, "
        "ally edges {ally_edges} (empty ally lists {ally_empty}), "
        "opposed edges {opposed_edges} (empty opposed lists {opposed_empty})".format(**kin_stats)
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
