def no_dash(text: str) -> str:
    if EM_DASH.search(text):
        raise SystemExit(f"em-dash law violation in generated output: {text!r}")
    return text


def join_mine() -> list[str]:
    """Every key must ground to exactly one mine row (die otherwise)."""
    mine = json.loads(MINE.read_text(encoding="utf-8"))["spheres"]
    counts: dict[str, int] = {}
    for name in mine:
        counts[name] = counts.get(name, 0) + 1
    spheres: list[str] = []
    for key in SPHERE_KEYS:
        n = counts.get(key, 0)
        if n == 0:
            raise SystemExit(f"ungrounded sphere key (not in mine): {key}")
        if n > 1:
            raise SystemExit(f"ambiguous sphere key {key}: mine holds it {n} times")
        spheres.append(key)
    return spheres


def gen_region(spheres: list[str]) -> str:
    """The generated region in LF; caller converts to the file's EOL."""
    lines = [BEGIN, REGEN, "local SPHERES: { string } = {"]
    for name in spheres:
        lines.append(f'\t"{name}",')
    lines.append("}")
    lines.append(END)
    # fix t35 2026-09-25: the region must end with its own newline. The first
    # run consumed the closing brace's newline (splice stops at close.end())
    # and the region supplied none after END, so the next line fused onto the
    # END comment and Worldgen.SPHERES = SPHERES became comment text: the
    # module exported a nil SPHERES. Evidence: working-tree Worldgen.luau
    # carried "-- END GENERATED (tools/gen_worldgen_spheres.py)Worldgen.SPHERES = SPHERES"
    # as one line; ZoneGate.luau (also t35) is the consumer that found it.
    # fix t41 2026-09-26: with the trailing newline here, the markers-exist
    # splice path must consume the single terminator that follows END, or
    # every rerun banks one more blank line (t41's first-run append plus this
    # trailing newline compounded; sandbox rerun census caught the growth).
    return "\n".join(lines) + "\n"


def splice(text: str, region_lf: str) -> str:
    eol = "\r\n" if "\r\n" in text else "\n"
    region = region_lf.replace("\n", eol)
    begin_at = text.find(BEGIN)
    end_at = text.find(END)
    if (begin_at == -1) != (end_at == -1):
        raise SystemExit("marker corruption: only one of BEGIN/END present")
    if begin_at != -1:
        # the region ends with its own newline (gen_region, t35 fix), so
        # consume the single terminator that follows END to stay byte-equal
        # on rerun: each unstripped rerun banked one more blank line (caught
        # by the t41 sandbox rerun census: 2 -> 3 -> 4 eols after END)
        rest = text[end_at + len(END):]
        if rest.startswith(eol):
            rest = rest[len(eol):]
        return text[:begin_at] + region + rest
    # first run: wrap the existing hand-folded SPHERES block with markers
    # (\r? because this CRLF file's lines end \r\n and re.M `$` will not
    # match before the \r)
    start = re.search(r"^local SPHERES: \{ string \} = \{\r?$", text, re.M)
    if not start:
        raise SystemExit("no BEGIN/END markers and no `local SPHERES` block found")
    close = re.search(r"^\}\r?\n", text[start.end():], re.M)
    if not close:
        raise SystemExit("SPHERES block has no closing `}` line")
    # consume the close's full newline: stopping at `$` would strand the \r
    # and rewrite that line ending to bare LF (caught by EOL census in t26)
    stop = start.end() + close.end()
    # the region carries its own trailing newline (t35 fix), and that is what
    # separates the END marker from whatever follows the block close (Worldgen
    # puts `Worldgen.SPHERES = SPHERES` directly after `}`, no blank line the
    # way ArtifactLore has). t41's earlier conditional append here COMPOUNDED
    # with that trailing newline into +1 eol per run; removed, the region's
    # own terminator is the single source of separation.
    return text[:start.start()] + region + text[stop:]


def main() -> int:
    spheres = join_mine()
    # the generated region is the only text this tool authors: it must carry
    # no em-dash. Pre-existing dashes elsewhere in the module stay untouched,
    # outside the markers, per the t26 house pattern.
    region = no_dash(gen_region(spheres))
    # read bytes and decode by hand: read_text() would translate the file's
    # CRLF to LF before the EOL detection below could see it, and the splice
    # would silently rewrite every line ending in the module.
    text = TARGET.read_bytes().decode("utf-8")
    out = splice(text, region)
    if out != text:
        TARGET.write_bytes(out.encode("utf-8"))
        print(f"spliced generated region into {TARGET}")
    else:
        print(f"{TARGET} already up to date (byte-identical rerun)")
    print(f"SPHERES pool: {len(spheres)} entries, all joined from df_spheres.json")
    return 0


if __name__ == "__main__":
    sys.exit(main())
