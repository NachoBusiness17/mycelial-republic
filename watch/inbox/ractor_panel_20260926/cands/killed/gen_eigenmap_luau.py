"""gen_eigenmap_luau - regenerate the GENERATED data block inside
roblox/src/shared/EigenMap.luau from a CATHEDRAL_CURVATURE_SCAN json.

The block is the single hand-off between the scan files and the in-game world
map: it carries the region eigen_centroids, curvature classes, cosines,
first-form hops from water_computer, the off-map regions, beta0 numbers, and
the water_first chain with each segment stamped by the wired graph (same
edge source as the HTML map: tools/cathedral_walk.py edges/bfs_hops). It
embeds the scan file's ts and sha256 so the built overlay is traceable to
exact bytes; tools/eigenmap_overlay_check.py verifies that trace and the
overlay math against the same json.

Usage:
  .venv/Scripts/python.exe tools/gen_eigenmap_luau.py            # newest scan
  .venv/Scripts/python.exe tools/gen_eigenmap_luau.py --scan <path>

Idempotent: rerunning on the same scan produces identical file bytes.

[RECORD COPY 2026-09-27] This is a byte-preserved record copy of
tools/gen_eigenmap_luau.py, the generator of ractor candidate eigenmap-one's
shared module (card eigenmap, panel 2026-09-26). The judge killed eigenmap-one
on the mirrored minimap; the build and its tooling were pruned from the repo
tree by the revise-eigenmap pass and the bytes moved here (the module it
generates, EigenMap.luau, sits beside this copy). Not maintained; running it
as-is writes nowhere because its ROOT now resolves against cands/killed/.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from tools.cathedral_walk import REGIONS, WATER_FIRST, bfs_hops, edges, load, owner_map  # noqa: E402

MODULE = ROOT / "roblox" / "src" / "shared" / "EigenMap.luau"
INBOX = ROOT / "watch" / "inbox"
BEGIN = "-- BEGIN GENERATED by tools/gen_eigenmap_luau.py -- do not hand-edit."
END = "-- END GENERATED"
SCHEMA = "cathedral.curvature.scan.v1"


def num(v: float) -> str:
    """Shortest float literal that round-trips (matches json.load doubles)."""
    return repr(float(v))


def newest_scan() -> Path:
    scans = sorted(INBOX.glob("CATHEDRAL_CURVATURE_SCAN_*.json"))
    if not scans:
        raise SystemExit("no CATHEDRAL_CURVATURE_SCAN_*.json in watch/inbox")
    return scans[-1]


def chain_segments(adj: dict[str, set], order: list[str]) -> list[dict]:
    segs = []
    for i in range(len(order) - 1):
        a, b = order[i], order[i + 1]
        path = bfs_hops(adj, a, b)
        if path is None:
            segs.append({"a": a, "b": b, "kind": "missing", "via": []})
        elif len(path) == 2:
            segs.append({"a": a, "b": b, "kind": "wired", "via": []})
        else:
            segs.append({"a": a, "b": b, "kind": "via", "via": path[1:-1]})
    return segs


def build_block(scan_path: Path) -> str:
    raw = scan_path.read_bytes()
    sha = hashlib.sha256(raw).hexdigest()
    scan = json.loads(raw.decode("utf-8"))
    if scan.get("schema") != SCHEMA:
        raise SystemExit(f"{scan_path.name}: schema {scan.get('schema')!r} != {SCHEMA!r}")
    cents = scan.get("eigen_centroids") or {}
    hops = scan.get("first_form_geodesics_from_water") or {}
    if not cents:
        raise SystemExit(f"{scan_path.name}: no eigen_centroids")

    rows = []
    for name in sorted(cents):
        ex, ey = cents[name][0], cents[name][1]
        region = scan.get("regions", {}).get(name, {})
        cos = region.get("cos")
        rows.append(
            "\t{{ name = \"{n}\", ex = {ex}, ey = {ey}, class = \"{c}\", {cos}hops = {h} }},".format(
                n=name,
                ex=num(ex),
                ey=num(ey),
                c=region.get("class", "?"),
                cos="" if cos is None else f"cos = {num(cos)}, ",
                h=hops.get(name, -1),
            )
        )

    mods = load()
    owner = owner_map(mods)
    wired = edges(mods, owner)
    adj: dict[str, set] = {r: set() for r in REGIONS}
    for a, b in wired:
        adj.setdefault(a, set()).add(b)
        adj.setdefault(b, set()).add(a)
    order = [r for r in WATER_FIRST if r in cents]
    segs = chain_segments(adj, order)
    seg_lines = []
    for s in segs:
        via = ""
        if s["via"]:
            inner = ", ".join(f'"{v}"' for v in s["via"])
            via = f", via = {{ {inner} }}"
        seg_lines.append(f'\t{{ a = "{s["a"]}", b = "{s["b"]}", kind = "{s["kind"]}"{via} }},')
    off_map = sorted(r for r in REGIONS if r not in cents)
    off_line = ", ".join(f'"{r}"' for r in off_map) or ""

    lines = [
        BEGIN,
        f"-- source: watch/inbox/{scan_path.name}",
        f"-- scan ts: {scan.get('ts', '?')}",
        f"-- scan sha256: {sha}",
        "-- regions sorted by name; hops = first-form geodesic from water_computer;",
        '-- chain = water_first order over mapped regions; kind stamped by the wired',
        "-- graph (tools/cathedral_walk.py), same edge source as the HTML map.",
        f'local SCAN_TS = "{scan.get("ts", "?")}"',
        f'local SCAN_SHA256 = "{sha}"',
        "local REGIONS: { RegionRow } = {",
        *rows,
        "}",
        "local CHAIN: { ChainSeg } = {",
        *seg_lines,
        "}",
        "local OFF_MAP: { string } = { " + off_line + " }",
        f"local BETA0_WIRED = {scan.get('beta0_wired_world', -1)}",
        f"local BETA0_INTENDED = {scan.get('beta0_intended_world', -1)}",
        END,
    ]
    return "\n".join(lines) + "\n"


def splice(module_path: Path, block: str) -> bool:
    text = module_path.read_text(encoding="utf-8")
    if BEGIN not in text or END not in text:
        raise SystemExit(f"{module_path}: GENERATED markers missing; refusing to write")
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    # END marker line ends the block; keep exactly one blank line before the
    # next hand-written section
    new_text = head + block + "\n\n" + tail.lstrip("\r\n")
    if new_text == text:
        return False
    module_path.write_text(new_text, encoding="utf-8", newline="\n")
    return True


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--scan", type=Path, default=None, help="scan json path (default: newest in watch/inbox)")
    args = ap.parse_args()
    scan_path = args.scan if args.scan else newest_scan()
    if not scan_path.is_absolute():
        scan_path = ROOT / scan_path
    block = build_block(scan_path)
    changed = splice(MODULE, block)
    n_regions = block.count("name = \"")
    n_segs = block.count("a = \"")
    print(f"scan: {scan_path.name}")
    print(f"block: {n_regions} regions, {n_segs} chain segments")
    print(f"{MODULE.relative_to(ROOT)}: {'rewritten' if changed else 'unchanged (idempotent)'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
